// Builds the Postgres (Supabase) schema from the SQLite migrations in drizzle/.
//   node scripts/make-postgres-schema.mjs     writes supabase/schema.sql
// The migrations are applied to an in-memory SQLite database; its final shape (tables, indexes, foreign keys and the
// data-scope triggers) is then written out as Postgres. Re-run it whenever a new migration is added.
//
// Security: every table lives in the private "ufs" schema, which Supabase does not expose through its public API, row-level
// security is on with no policies, and all access is revoked from the public "anon" and "authenticated" roles. The only way
// in is the service-role-only function in supabase/executor.sql, so the publishable key alone can never read HR data.
import { DatabaseSync } from "node:sqlite";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const sqlite = new DatabaseSync(":memory:");
for (const name of readdirSync(path.join(root, "drizzle")).filter((file) => file.endsWith(".sql")).sort()) {
  for (const statement of readFileSync(path.join(root, "drizzle", name), "utf8").split("--> statement-breakpoint")) if (statement.trim()) sqlite.exec(statement);
}

const q = (identifier) => `"${identifier}"`;
const t = (table) => `ufs.${q(table)}`;
const typeOf = (declared) => {
  const type = declared.toLowerCase();
  if (type === "text") return "text";
  if (type === "integer") return "bigint";
  if (type === "real") return "double precision";
  throw new Error(`No Postgres type for "${declared}"`);
};
const defaultOf = (value) => {
  if (value === null) return "";
  if (/^'.*'$/s.test(value) || /^-?\d+(\.\d+)?$/.test(value)) return ` default ${value}`;
  throw new Error(`Unsupported default ${value}`);
};

const tables = sqlite.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all().map((row) => row.name);
const out = [
  "-- Generated by scripts/make-postgres-schema.mjs from drizzle/*.sql. Do not edit by hand.",
  "-- Run once in the Supabase SQL editor (or with the SQL tool) before switching the app to Supabase.",
  "",
  "create schema if not exists ufs;",
  "revoke all on schema ufs from public, anon, authenticated;",
  "alter default privileges in schema ufs revoke all on tables from public, anon, authenticated;",
  "alter default privileges in schema ufs revoke all on functions from public, anon, authenticated;",
  "",
];
const foreignKeys = [];
for (const table of tables) {
  const columns = sqlite.prepare(`PRAGMA table_info(${q(table)})`).all();
  const primary = columns.filter((column) => column.pk > 0).sort((a, b) => a.pk - b.pk).map((column) => column.name);
  const lines = columns.map((column) => `  ${q(column.name)} ${typeOf(column.type)}${column.notnull || primary.includes(column.name) ? " not null" : ""}${defaultOf(column.dflt_value)}`);
  if (primary.length) lines.push(`  primary key (${primary.map(q).join(", ")})`);
  out.push(
    `create table ${t(table)} (\n${lines.join(",\n")}\n);`,
    `alter table ${t(table)} enable row level security; -- no policies on purpose: the Data API sees nothing`,
    `revoke all on ${t(table)} from public, anon, authenticated;`,
    "",
  );
  for (const fk of sqlite.prepare(`PRAGMA foreign_key_list(${q(table)})`).all()) foreignKeys.push({ table, from: fk.from, to: fk.table, toColumn: fk.to });
}
for (const [index, fk] of foreignKeys.entries()) {
  out.push(`alter table ${t(fk.table)} add constraint ${q(`fk_${fk.table}_${fk.from}_${index}`)} foreign key (${q(fk.from)}) references ${t(fk.to)} (${q(fk.toColumn)});`);
}
out.push("");
for (const index of sqlite.prepare("SELECT name,sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY name").all()) {
  out.push(index.sql.replace(/`/g, '"').replace(/\s+/g, " ").replace(/\bON "(\w+)"/i, 'on ufs."$1"') + ";");
}
out.push("");

// SQLite triggers have one shape here: BEFORE INSERT/UPDATE ... WHEN <condition> BEGIN SELECT RAISE(ABORT,'message'); END.
let triggerCount = 0;
for (const trigger of sqlite.prepare("SELECT name,sql FROM sqlite_master WHERE type='trigger' ORDER BY name").all()) {
  const match = /CREATE TRIGGER (\w+)\s+BEFORE (INSERT|UPDATE|DELETE) ON (\w+)\s+WHEN ([\s\S]*?)\s+BEGIN SELECT RAISE\(ABORT, '([^']*)'\); END/.exec(trigger.sql);
  if (!match) throw new Error(`Unrecognised trigger shape: ${trigger.name}`);
  const [, name, event, table, condition, message] = match;
  out.push(
    `create function ufs.${q(`${name}_fn`)}() returns trigger language plpgsql set search_path = ufs, pg_temp as $fn$`,
    `begin`,
    `  if ${condition} then raise exception '${message}'; end if;`,
    `  return new;`,
    `end $fn$;`,
    `create trigger ${q(name)} before ${event.toLowerCase()} on ${t(table)} for each row execute function ufs.${q(`${name}_fn`)}();`,
    "",
  );
  triggerCount++;
}
out.push("revoke all on all functions in schema ufs from public, anon, authenticated;", "");

mkdirSync(path.join(root, "supabase"), { recursive: true });
writeFileSync(path.join(root, "supabase/schema.sql"), out.join("\n"));
console.log(`Wrote supabase/schema.sql: ${tables.length} tables, ${foreignKeys.length} foreign keys, ${triggerCount} triggers.`);
